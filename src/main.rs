#![warn(clippy::perf)]
#![deny(clippy::clone_on_ref_ptr)]
#![deny(clippy::unwrap_used)]
#![deny(clippy::expect_used)]
#![deny(warnings)]
#![deny(clippy::all)]
#![deny(missing_docs)]

include!("main_entry/help_i18n.rs");
include!("main_entry/cli_runtime.rs");
