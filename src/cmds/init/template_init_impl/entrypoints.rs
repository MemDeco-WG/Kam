/// Initialize a project implementation from a template source.
///
/// # Errors
///
/// Returns `Err(KamError)` if filesystem operations, archive extraction, or template rendering fail.
pub fn init_impl(path: &Path, params: &mut InitImplParams<'_>) -> Result<(), KamError> {
    let temp_dir = tempfile::tempdir().map_err(KamError::Io)?;
    let template_path = resolve_template_source(params.impl_source, &temp_dir)?;
    let archive_id = params
        .explicit_template_id
        .map_or_else(|| "template".to_string(), ToString::to_string);

    let template_kam_path = template_path.join("kam.toml");
    if template_kam_path.exists() {
        merge_template_defaults(&template_kam_path, params.template_vars)?;
    }

    let mut kt = new_project_kam_toml(params, &archive_id);
    let kam_vars = take_kam_vars(params.template_vars);
    if !kam_vars.is_empty() {
        kt.apply_vars(kam_vars)?;
    }

    if !path.exists() {
        fs::create_dir_all(path).map_err(KamError::Io)?;
    }

    merge_kam_toml_vars(&kt, params.template_vars);

    // Check if kam.toml exists BEFORE copy_and_replace
    let kam_toml_path = path.join("kam.toml");
    let kam_toml_existed_before_copy = kam_toml_path.exists();

    // Copy files (respect build.include/build.exclude if present)
    let excludes = kt.kam.build.as_ref().and_then(|b| b.exclude.as_deref());
    let includes = kt.kam.build.as_ref().and_then(|b| b.include.as_deref());

    crate::template::TemplateManager::copy_and_replace_with_rules(
        &template_path,
        path,
        params.template_vars,
        params.force,
        &archive_id,
        excludes,
        includes,
    )?;

    // If kam.toml doesn't exist (not in template), write the generated one
    if !kam_toml_path.exists() {
        kt.write_to_dir(path)?;
    }

    render_project_kam_toml(
        &kam_toml_path,
        params,
        &mut kt,
        kam_toml_existed_before_copy,
    )?;
    write_template_env_file(path, &kt, params.template_vars)?;

    Ok(())
}

