/// Create a project from a named template.
///
/// # Errors
///
/// Returns `Err(KamError)` when the template cannot be found or I/O/rendering fails.
// TODO: split this function into smaller units to reduce complexity
/// AUTO-GENERATED BY Kam/scripts/add_missing_docs.py: placeholder documentation for public function 'init_template'. Replace with real documentation. (2025-12-30T22:23:21Z)
#[allow(clippy::too_many_lines)]
pub fn init_template(path: &Path, params: &InitTemplateParams<'_>) -> Result<(), KamError> {
    let mut template_vars = crate::template::TemplateManager::parse_template_vars(params.var)?;

    let template_spec = params
        .impl_template
        .as_deref()
        .unwrap_or("kam_template")
        .to_string();

    // Strategy:
    // 1. Check if `template_spec` exists as a local file or directory (relative to CWD).
    // 2. Check if `template_spec` exists in built-in assets.
    // 3. Check project-local `tmpl/` or `templates/` dirs.
    // 4. Check global template cache.
    // 5. If NOT found and `template_spec` does NOT end with `_template` or look like a file archive,
    //    append `_template` and retry steps 2-3 (but not step 1 again, usually).

    let mut potential_names = vec![template_spec.clone()];

    // If it doesn't have an extension and doesn't end in _template, try appending it as a fallback
    let is_archive_or_path = template_spec.contains('/')
        || template_spec.contains('\\')
        || template_spec.to_ascii_lowercase().ends_with(".tar.gz")
        || std::path::Path::new(&template_spec)
            .extension()
            .is_some_and(|ext| ext.eq_ignore_ascii_case("zip"));

    if !template_spec.ends_with("_template") && !is_archive_or_path {
        potential_names.push(format!("{template_spec}_template"));
    }

    for spec in &potential_names {
        // 1. Direct local path (only for the first/raw spec, or if we really want to support 'foo_template' local dir)
        let spec_path = Path::new(spec);
        if spec_path.exists() {
            return init_from_source(path, params, &mut template_vars, spec_path, spec.as_str());
        }

        // 2. Built-in assets
        // We typically store built-ins as "kam_template.tar.gz" -> check spec
        // If the spec is "kam", we might be in the second iteration where spec="kam_template"
        let asset_name = format!("{spec}.tar.gz");
        if let Some(asset) = crate::assets::tmpl::TmplAssets::get(&asset_name) {
            let temp_dir = tempfile::tempdir().map_err(KamError::Io)?;
            let temp_path = temp_dir.path().join(format!("{spec}.tar.gz"));
            fs::write(&temp_path, &asset.data).map_err(KamError::Io)?;

            return init_from_source(path, params, &mut template_vars, &temp_path, spec.as_str());
        }

        // 3. Project-local folder search (tmpl/ or templates/)
        for candidate in project_local_template_candidates(spec) {
            if candidate.exists() {
                return init_from_source(
                    path,
                    params,
                    &mut template_vars,
                    &candidate,
                    spec.as_str(),
                );
            }
        }

        // 4. Cache
        if let Ok(Some(cached_path)) =
            crate::template::TemplateCacheManager::resolve_template_path(spec)
        {
            return init_from_source(
                path,
                params,
                &mut template_vars,
                &cached_path,
                spec.as_str(),
            );
        }
    }

    // Final failure
    Err(KamError::TemplateNotFound(format!(
        "Template '{template_spec}' not found in built-in assets, local path, cache, or project directories."
    )))
}

#[cfg(test)]
mod tests {
    use super::merge_template_defaults;
    use std::collections::HashMap;

    #[test]
    fn merge_template_defaults_reads_kam_tmpl_variables() {
        let temp_dir = tempfile::tempdir().expect("tempdir");
        let kam_toml_path = temp_dir.path().join("kam.toml");
        std::fs::write(
            &kam_toml_path,
            r#"
[prop]
id = "example_template"
name = "Example Template"
version = "v1.0.0"
versionCode = 1
description = "Example"

[kam]
module_type = "template"

[kam.tmpl.variables.repository]
var_type = "string"
required = false
default = "https://github.com/example/repo"
"#,
        )
        .expect("write kam.toml");

        let mut vars = HashMap::new();
        merge_template_defaults(&kam_toml_path, &mut vars).expect("merge defaults");

        assert_eq!(
            vars.get("repository").map(String::as_str),
            Some("https://github.com/example/repo")
        );
    }

    #[test]
    fn merge_template_defaults_does_not_override_user_vars() {
        let temp_dir = tempfile::tempdir().expect("tempdir");
        let kam_toml_path = temp_dir.path().join("kam.toml");
        std::fs::write(
            &kam_toml_path,
            r#"
[prop]
id = "example_template"
name = "Example Template"
version = "v1.0.0"
versionCode = 1
description = "Example"

[kam]
module_type = "template"

[kam.tmpl.variables.repository]
var_type = "string"
required = false
default = "https://github.com/example/repo"
"#,
        )
        .expect("write kam.toml");

        let mut vars = HashMap::from([(
            "repository".to_string(),
            "https://github.com/user/repo".to_string(),
        )]);
        merge_template_defaults(&kam_toml_path, &mut vars).expect("merge defaults");

        assert_eq!(
            vars.get("repository").map(String::as_str),
            Some("https://github.com/user/repo")
        );
    }
}
